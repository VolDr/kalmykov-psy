const capitalize = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);

/** Разметка schema.org FAQPage: вопросы с заглавной буквы, ответы без markdown. */
export function sessionFaqJsonLd(): string {
	return JSON.stringify({
		'@context': 'https://schema.org',
		'@type': 'FAQPage',
		mainEntity: sessionFaq.map((item) => ({
			'@type': 'Question',
			name: capitalize(item.q),
			acceptedAnswer: {
				'@type': 'Answer',
				text: item.a.replace(/\*\*/g, '')
			}
		}))
	}).replace(/</g, '\\u003c');
}
