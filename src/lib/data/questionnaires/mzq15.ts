/** Прямое описательное среднее согласия (1–5), не диагностический балл.
 * В статье Hausberg et al. (2012) использовалось обратное направление итогового показателя.
 */
export function scoreMzq15(answers: Record<string, number>) {
	const values = mzq15Questions.map((item) => answers[item.id]);
	if (values.some((value) => !Number.isInteger(value) || value < 1 || value > 5)) return null;
	const total = values.reduce((sum, value) => sum + value, 0);
	return {
		total,
		mean: total / mzq15Questions.length,
		subscales: mzq15Domains.map((domain) => ({
			name: domain.name,
			value: domain.questionIds.reduce((sum, id) => sum + answers[id], 0) / domain.questionIds.length,
			max: 5,
			tone: 'neutral' as const,
			description: domain.description
		}))
	};
}
