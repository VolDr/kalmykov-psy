-- Шаг, у которого не выполнилось условие, раньше писался как 'cancelled', потом
-- как 'sent' — оба варианта врут статистике. Отдельный терминальный статус.
--
-- ALTER TYPE ... ADD VALUE нельзя использовать в той же транзакции, где значение
-- добавлено, поэтому миграция состоит ровно из одного этого шага: приложение
-- начнёт писать 'skipped' уже после коммита.
ALTER TYPE "public"."bot_scheduled_step_status" ADD VALUE IF NOT EXISTS 'skipped' AFTER 'sent';
