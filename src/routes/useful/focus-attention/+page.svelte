	import { reachGoal } from '$lib/metrika';
	import { setupLeadMagnetTracking } from '$lib/client/leadMagnetTracking';
	import { landOnHashTarget } from '$lib/hashLanding';
	import ButtonSvg from '$lib/components/ui/ButtonSvg.svelte';

	let { data } = $props();

