		reachGoal('lm_opened');

		if (!window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
			const targets = document.querySelectorAll('[data-reveal]');
			targets.forEach((el) => {
				(el as HTMLElement).style.opacity = '0';
				(el as HTMLElement).style.transform = 'translateY(18px)';
