					'opacity 640ms cubic-bezier(0.16,1,0.3,1), transform 640ms cubic-bezier(0.16,1,0.3,1)';
			});
			const obs = new IntersectionObserver(
				(entries) => {
					entries.forEach((e) => {
						if (e.isIntersecting) {
							(e.target as HTMLElement).style.opacity = '1';
							(e.target as HTMLElement).style.transform = '';
							obs.unobserve(e.target);
						}
					});
				},
				{ threshold: 0.07 }
			);
			targets.forEach((el) => obs.observe(el));
		}

		initScrollGoals();

		const observer = new IntersectionObserver(
			([entry]) => {
				if (!entry.isIntersecting) return;
				reachGoal('lead_cta_seen');
				observer.disconnect();
			},
			{ threshold: 0.5 }
		);
		if (ctaSection) observer.observe(ctaSection);

		if (sbClientId) {
			cleanupTracking = setupLeadMagnetTracking({
				leadMagnet: 'focus',
				readThreshold: 75,
				minimumReadingTimeMs: 30_000
			});
		}
	});

	afterNavigate(({ to }) => {
		if (to?.url.hash === '#acquaintance' && ctaSection) {
			landOnHashTarget(ctaSection);
		}
	});

	onDestroy(() => {
		cleanupTracking?.();
	});
</script>

